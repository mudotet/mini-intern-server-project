import { test, expect } from '@playwright/test';

test('nested navigation, declaration outline and export cancellation preserve the workspace', async ({ page, request }) => {
  await page.goto('/');
  await expect(page.getByText('Schema hợp lệ', { exact: true })).toBeVisible();
  const navigation = page.getByRole('navigation', { name: 'Danh sách schema' });
  const gameFolder = navigation.getByRole('button', { name: 'Thư mục game', exact: true });
  const blueprintFolder = navigation.getByRole('button', { name: 'Thư mục game/blueprint', exact: true });
  const blueprintFile = navigation.getByRole('button', { name: 'Mở game/blueprint/shop.proto', exact: true });
  await expect(gameFolder).toHaveAttribute('aria-expanded', 'true');
  await expect(blueprintFolder).toHaveAttribute('aria-expanded', 'true');
  await expect(blueprintFile).toHaveAttribute('aria-current', 'page');
  await blueprintFolder.click();
  await expect(blueprintFolder).toHaveAttribute('aria-expanded', 'false');
  await expect(blueprintFile).not.toBeVisible();
  await blueprintFolder.click();
  await expect(blueprintFile).toBeVisible();
  await gameFolder.click();
  await expect(gameFolder).toHaveAttribute('aria-expanded', 'false');
  await expect(blueprintFolder).not.toBeVisible();
  await gameFolder.click();

  await blueprintFolder.click();
  await expect(blueprintFolder).toHaveAttribute('aria-expanded', 'false');
  const search = page.getByRole('textbox', { name: 'Tìm schema' });
  await search.fill('shop.proto');
  const modelFolder = navigation.getByRole('button', { name: 'Thư mục game/model', exact: true });
  const modelFile = navigation.getByRole('button', { name: 'Mở game/model/shop.proto', exact: true });
  await expect(blueprintFile).toBeVisible();
  await expect(modelFile).toBeVisible();
  await expect(modelFolder).toHaveAttribute('aria-expanded', 'true');
  await expect(navigation.getByRole('button', { name: 'Mở game/error.proto', exact: true })).not.toBeVisible();
  await modelFile.click();
  await search.fill('');
  await expect(modelFolder).toHaveAttribute('aria-expanded', 'true');
  await expect(modelFile).toHaveAttribute('aria-current', 'page');
  await expect(blueprintFolder).toHaveAttribute('aria-expanded', 'false');
  await expect(blueprintFile).not.toBeVisible();
  await blueprintFolder.click();

  const outline = page.getByRole('navigation', { name: 'Cấu trúc file' });
  const target = outline.getByRole('button', { name: 'Chọn game.model.ShopDailyOfferSnapshotProto', exact: true });
  await target.click();
  await expect(target).toHaveAttribute('aria-current', 'true');
  await expect(page.getByRole('heading', { name: 'ShopDailyOfferSnapshotProto', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Chỉnh sửa items', exact: true })).toBeVisible();
  await blueprintFile.click();
  await outline.getByRole('button', { name: 'Chọn game.blueprint.ShopPackage.Price', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Price', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Chỉnh sửa currency', exact: true })).toBeVisible();

  const before = await page.evaluate(() => JSON.parse(localStorage.getItem('proto-studio-workspace-v1')).files);
  const baseline = await (await request.get('/api/workspace')).json();
  let downloads = 0;
  page.on('download', () => downloads++);
  await page.getByRole('button', { name: 'Xuất ZIP', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Xuất workspace' });
  await expect(dialog).toContainText(`${baseline.files.length} file`);
  await expect(dialog).toContainText('0 file');
  await expect(dialog).toContainText('cấu trúc thư mục');
  await dialog.getByRole('button', { name: 'Hủy', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect(downloads).toBe(0);
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('proto-studio-workspace-v1')).files)).toEqual(before);
});
